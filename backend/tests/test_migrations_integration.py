"""Migrations against a real, disposable Postgres (integration).

Runs upgrade head -> downgrade base -> upgrade head to prove reversibility, then
`alembic check` to assert the models have no un-migrated drift. This is the class
of bug create_all-based unit tests can't catch.

Run with the compose stack up: `pytest -m integration tests/test_migrations_integration.py`.
"""

from __future__ import annotations

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import create_engine, text

pytestmark = pytest.mark.integration

_BASE = "postgresql+psycopg://keystone:keystone@postgres:5432"
_ADMIN_URL = f"{_BASE}/keystone"
_TEST_DB = "keystone_migtest"
_TEST_URL = f"{_BASE}/{_TEST_DB}"


@pytest.fixture
def temp_db():
    admin = create_engine(_ADMIN_URL, isolation_level="AUTOCOMMIT")
    with admin.connect() as c:
        c.execute(text(f"DROP DATABASE IF EXISTS {_TEST_DB} WITH (FORCE)"))
        c.execute(text(f"CREATE DATABASE {_TEST_DB}"))
    try:
        yield _TEST_URL
    finally:
        with admin.connect() as c:
            c.execute(text(f"DROP DATABASE IF EXISTS {_TEST_DB} WITH (FORCE)"))
        admin.dispose()


def _cfg(url, monkeypatch):
    import keystone_api.config as cfgmod

    base = cfgmod.get_settings()
    monkeypatch.setattr(
        cfgmod, "get_settings", lambda: base.model_copy(update={"database_url": url})
    )
    return Config("alembic.ini")


def test_migrations_roundtrip(temp_db, monkeypatch):
    cfg = _cfg(temp_db, monkeypatch)
    command.upgrade(cfg, "head")
    command.downgrade(cfg, "base")
    command.upgrade(cfg, "head")  # reversible + re-appliable


def test_no_model_migration_drift(temp_db, monkeypatch):
    cfg = _cfg(temp_db, monkeypatch)
    command.upgrade(cfg, "head")
    # raises AutogenerateDiffsDetected if a model change isn't captured in a migration
    command.check(cfg)
